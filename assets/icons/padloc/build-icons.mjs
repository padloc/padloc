import { readFileSync, writeFileSync } from "node:fs";

const names = Object.keys(JSON.parse(readFileSync(new URL("usage.json", import.meta.url), "utf8")));
const entries = names.map((name) => {
    const source = readFileSync(new URL(`${name}.svg`, import.meta.url), "utf8");
    const body = source
        .replace(/^.*?<svg[^>]*>|<\/svg>.*$/gs, "")
        .trim()
        // Keep smaller interior strokes proportional to the inherited stroke width.
        .replace(/stroke-width="([\d.]+)"/g, (_, width) => {
            const ratio = (Number(width) / 1.75).toFixed(8);
            return `style="stroke-width: calc(var(--icon-stroke-width, 1.75px) * ${ratio})"`;
        });

    if (body.includes("`") || body.includes("${")) {
        throw new Error(`Unexpected template syntax in ${name}`);
    }

    return `    ${JSON.stringify(name)}: svg\`${body}\`,`;
});

writeFileSync(
    new URL("../../../packages/app/src/lib/icons.ts", import.meta.url),
    [
        "// Generated by assets/icons/padloc/build-icons.mjs. Edit the SVG sources instead.",
        'import { svg, TemplateResult } from "lit";',
        "",
        "export const icons: Record<string, TemplateResult> = {",
        ...entries,
        "};",
        "",
    ].join("\n")
);
console.log(`Generated ${names.length} icon templates.`);
