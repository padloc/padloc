"""Generate Lit SVG templates from the editable Padloc icon sources."""
from pathlib import Path
import json
import re

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
names = json.loads((HERE / "usage.json").read_text())
lines = ['// Generated by assets/icons/padloc/build-icons.py. Edit the SVG sources instead.',
         'import { svg, TemplateResult } from "lit";', '',
         'export const icons: Record<string, TemplateResult> = {']
for name in names:
    source = (HERE / f"{name}.svg").read_text()
    body = re.sub(r'^.*?<svg[^>]*>|</svg>.*$', '', source, flags=re.S).strip()
    # Keep smaller interior strokes proportional to the selected weight.
    body = re.sub(r'stroke-width="([\d.]+)"',
                  lambda m: f'style="stroke-width: calc(var(--icon-stroke-width, 1.75px) * {float(m[1]) / 1.75:.8f})"', body)
    if '`' in body or '${' in body:
        raise ValueError(f"Unexpected template syntax in {name}")
    lines.append(f'    "{name}": svg`{body}`,')
lines.extend(['};', ''])
(ROOT / "packages/app/src/lib/icons.ts").write_text('\n'.join(lines))
print(f"Generated {len(names)} icon templates.")
